"""현장 진단 사례 글에서 개인정보가 의심되는 줄을 가려낸다. 자료를 만들 때(build_care)와 올리기 전 점검(check_site)이 같은 기준을 쓴다."""
import re

# 직함이 붙은 이름, 전화번호, 번지·도로명 주소, 개요의 일시·장소·출장자 줄
PRIVATE_LINE = re.compile(
    r"\d{2,3}-\d{3,4}-\d{4}"
    r"|[가-힣]{2,4}\s?(팀장|계장|과장|소장|센터장|지도사|지도관|연구사|연구관|기술위원|위원|주무관|서기관|사무관|박사|교수|대표|이장|농가주)"
    r"|[가-힣]+길\s?\d+|[가-힣]+로\s?\d+번?길|\d+\s?번지|[가-힣]+(읍|면)\s[가-힣]+리\s?\d|아파트\s?\d|\d+\s?동\s?\d+\s?호"
    r"|농\s?가\s?명|성\s?명\s?:|연\s?락\s?처|주\s?소\s?:|출\s?장\s?자|보\s?고\s?자|입\s?회\s?자|장\s?소\s?:|일\s?시\s?:"
    # 원문이 '김○○'처럼 다 가린 이름은 두고, '김○태'·'김은○'처럼 두 글자가 드러난 이름은 뺀다
    r"|(?<![가-힣])[가-힣][○◯][가-힣](?![가-힣])|(?<![가-힣])[가-힣]{2}[○◯](?![가-힣○◯])"
)

# '양해열 농가', '김광호 씨' 처럼 성씨로 시작하는 세 글자 이름 뒤에 농가·씨 등이 오는 경우
SURNAMES = set("김이박최정강조윤장임한오서신권황안송류유전홍고문양손배백허남심노하곽성차주우구민진나지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉사부")
NAME_BEFORE = re.compile(r"(?<![가-힣])([가-힣]{3})\s?(농가|씨|님|농장주|어르신)(?![가-힣])")
# '민원인 박종식은' 처럼 민원인 등 뒤에 이름이 오는 경우
NAME_AFTER = re.compile(r"(?:민원인|의뢰인|신청인|농가주|농장주)\s?\(?([가-힣]{3})(?=[은는이가의께,)\s]|씨|농가|$)")
NOT_NAME_END = set("한과인의은는로형여을를이가에도만")
NOT_NAME = {"민원인", "나머지", "재배자", "관계자", "생산자", "담당자", "대표자", "신청인", "이웃집", "이웃농", "고추밭",
            "하우스", "과수원", "비닐하", "포장에", "농장의", "자신의", "본인의"}


def is_private(text):
    if PRIVATE_LINE.search(text):
        return True
    for m in [*NAME_BEFORE.finditer(text), *NAME_AFTER.finditer(text)]:
        name = m.group(1)
        if name[0] in SURNAMES and name[-1] not in NOT_NAME_END and name not in NOT_NAME:
            return True
    return False
